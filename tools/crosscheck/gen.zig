//! Generator CLI for the differential test bench: writes the body file for a
//! seed. The program model, generation and printing live in program.zig, which
//! the reducer (reduce.zig) shares. See docs/crosscheck.md.
//!
//! Usage: crosscheck-gen --seed=<u64> [--include-known-findings] [--floats] <out.zig>

const std = @import("std");
const program = @import("program.zig");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;

    const args = try init.minimal.args.toSlice(arena);
    var seed: ?u64 = null;
    var out_path: ?[]const u8 = null;
    var include_known = false;
    var floats = false;
    for (args[1..]) |arg| {
        if (std.mem.startsWith(u8, arg, "--seed=")) {
            seed = std.fmt.parseInt(u64, arg["--seed=".len..], 10) catch {
                std.debug.print("crosscheck-gen: bad --seed value '{s}'\n", .{arg["--seed=".len..]});
                std.process.exit(2);
            };
        } else if (std.mem.eql(u8, arg, "--include-known-findings")) {
            include_known = true;
        } else if (std.mem.eql(u8, arg, "--floats")) {
            floats = true;
        } else if (std.mem.startsWith(u8, arg, "-")) {
            std.debug.print("crosscheck-gen: unknown option '{s}'\n", .{arg});
            std.process.exit(2);
        } else if (out_path == null) {
            out_path = arg;
        } else {
            std.debug.print("crosscheck-gen: unexpected extra argument '{s}'\n", .{arg});
            std.process.exit(2);
        }
    }
    const usage_text = "usage: crosscheck-gen --seed=<u64> [--include-known-findings] [--floats] <out.zig>\n";
    const sd = seed orelse {
        std.debug.print(usage_text, .{});
        std.process.exit(2);
    };
    const path = out_path orelse {
        std.debug.print(usage_text, .{});
        std.process.exit(2);
    };

    const prog = try program.generate(arena, sd, .{ .include_known = include_known, .floats = floats });
    var w: std.Io.Writer.Allocating = .init(arena);
    try w.writer.print(
        \\// Generated by tools/crosscheck/gen.zig — do not edit.
        \\// seed={d} locals={d} statements={d}
        \\//
        \\// body(a, b) is a random total i32 program. Compiled for the GPU
        \\// (src/engine/crosscheck_harness.zig) and the CPU
        \\// (tools/crosscheck/driver.zig); the driver feeds both the same inputs
        \\// and compares.
        \\
    , .{ sd, prog.nvars, program.countStmts(prog.stmts) });
    if (include_known) try w.writer.writeAll("// Generated with --include-known-findings (docs/crosscheck.md).\n");
    if (floats) try w.writer.writeAll("// Generated with --floats (docs/crosscheck-float-policy.md).\n");
    try w.writer.print("pub const seed: u64 = {d};\n\n", .{sd});
    const text = try program.render(arena, &prog, w.written());
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = path, .data = text });
}
