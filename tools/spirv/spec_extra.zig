//! The SPIR-V grammar's value-enum and bit-enum enumerants that the vendored
//! tables in spec.zig lack, consulted with them through `reader.enumerants`
//! (and `reader.enumerant` / `reader.enumerantByName`), which reader.zig,
//! dis.zig and asm.zig use for every enumerant lookup.
//!
//! Why: Zig's tools/gen_spirv_spec.zig, which generated spec.zig, keeps only
//! part of the Khronos grammar's enumerants: it drops nearly every
//! vendor-tagged one (GOOGLE, NV, AMD(X), INTEL, ALTERA, QCOM, ARM, VALVE,
//! SAMSUNG, ...) and a few core ones besides (the Sampled1D / Image1D
//! capabilities, RoundingModeRTE / RoundingModeRTZ, the FPDenormMode and
//! FPOperationMode values, ...). An enumerant the tables do not know has no
//! known parameters, so the reader used to decode e.g. DXC's
//! `OpDecorateString %v UserTypeGOOGLE "structuredbuffer:<uint>"` (emitted
//! for every resource under `-fspv-reflect`) as a parameterless decoration
//! and refuse the valid module as malformed ("trailing word(s) the grammar
//! does not account for"). spec.zig stays verbatim; the gap is closed here.
//!
//! Generated once from the Khronos grammar spirv.core.grammar.json (SPIR-V
//! 1.6 revision 7, the grammar SPIRV-DESIGN cites) by listing, per operand
//! kind, every enumerant whose VALUE no entry of spec.zig's table for that
//! kind has, with its grammar parameters, in grammar order. Left out: the
//! bit enums' `None` (0) entries (dis.zig and asm.zig spell 0 as `None`
//! themselves), aliases (an alias shares its enumerant's value; in a bit
//! enum a second entry with the same value would decode its parameters
//! twice), and the GatherModes kind, which has no spec.OperandKind (only
//! vendor opcodes that spec.Opcode lacks use it). The names are the
//! grammar's, so `dis` prints them as spirv-dis does. Tests in reader.zig
//! check that no entry duplicates a vendored value and that every bit is a
//! single new bit. Only decoding and naming come from here: lower.zig still
//! decides per decoration, capability or mode what it supports.
//!
//! The enumerant names and numbers below are data from that grammar file,
//! whose header reads "Copyright: 2014-2024 The Khronos Group Inc.",
//! "License: MIT" (the same terms as spec.zig's notice).

