//! The one-instruction probe kernels: one tiny compute module per mapped
//! GLSL.std.450 / OpenCL.std instruction and per arithmetic, comparison,
//! conversion, bit, vector and composite instruction, at the widths and
//! vector shapes the lowering distinguishes, written as spvasm text for
//! tools/spirv/asm.zig. Each is lowered on its own and built into a compute
//! pipeline by Metal (tools/spirv_probe.zig + tools/spirv/run_probes.sh),
//! so a mapping Metal's runtime compiler rejects is attributable to exactly
//! one instruction at one type; the outcome table is in docs/spirv.md.
//!
//! Module shape (Vulkan flavour): `Logical GLSL450`, one GLCompute entry
//! point named after the probe, operands loaded from read-only Block buffers
//! of runtime arrays at bindings 0..2 indexed by GlobalInvocationId.x, the
//! result `%r` stored to binding 3 (a bool result as 0/1 through OpSelect, a
//! `{T, T}` struct result as the sum of its members). OpenCL flavour:
//! `Physical64 OpenCL`, a Kernel entry point whose parameters are
//! CrossWorkgroup pointers, a `<3 x u64>` GlobalInvocationId and
//! OpInBoundsPtrAccessChain, as Zig's `spirv64-opencl` output has.

const std = @import("std");
const Allocator = std.mem.Allocator;

pub const Flavour = enum { vulkan, opencl };

pub const Probe = struct {
    /// Kernel (and entry point) name; unique.
    name: []const u8,
    flavour: Flavour = .vulkan,
    /// Type names of the operands `%a`, `%b`, `%c` (`f32`, `v4f32`, ...).
    operands: []const []const u8,
    /// Type of `%r`; `S_<T>` is a `{ T, T }` struct.
    result: []const u8,
    /// Lines defining `%r` from `%a`, `%b`, `%c` (`%glsl` / `%ocl` are the
    /// imported sets).
    body: []const u8,
    /// Extra OpDecorate lines (on body ids: `OpDecorate %r SaturatedConversion`).
    decorations: []const u8 = "",
    /// Extra type and constant lines (`%Sq = OpTypeStruct %u32 %v4u32`).
    types: []const u8 = "",
    /// The lowering refuses this probe on purpose, with a message containing
    /// this text: the construct crashes or fails Metal's compiler (stage-4
    /// probes; the outcome row in EXPECTED.txt is the refusal).
    refused: ?[]const u8 = null,
};

const scalars = [_]struct { name: []const u8, decl: []const u8, size: u32 }{
    .{ .name = "bool", .decl = "OpTypeBool", .size = 1 },
    .{ .name = "u8", .decl = "OpTypeInt 8 0", .size = 1 },
    .{ .name = "i8", .decl = "OpTypeInt 8 1", .size = 1 },
    .{ .name = "u16", .decl = "OpTypeInt 16 0", .size = 2 },
    .{ .name = "i16", .decl = "OpTypeInt 16 1", .size = 2 },
    .{ .name = "u32", .decl = "OpTypeInt 32 0", .size = 4 },
    .{ .name = "i32", .decl = "OpTypeInt 32 1", .size = 4 },
    .{ .name = "u64", .decl = "OpTypeInt 64 0", .size = 8 },
    .{ .name = "i64", .decl = "OpTypeInt 64 1", .size = 8 },
    .{ .name = "f16", .decl = "OpTypeFloat 16", .size = 2 },
    .{ .name = "f32", .decl = "OpTypeFloat 32", .size = 4 },
};

fn scalarSize(name: []const u8) u32 {
    for (scalars) |s| if (std.mem.eql(u8, s.name, name)) return s.size;
    unreachable;
}

/// `v4f32` -> (4, "f32"); `f32` -> (1, "f32").
fn split(t: []const u8) struct { n: u32, scalar: []const u8 } {
    if (t.len > 2 and t[0] == 'v' and std.ascii.isDigit(t[1])) return .{ .n = t[1] - '0', .scalar = t[2..] };
    return .{ .n = 1, .scalar = t };
}

/// AIR allocation size: a vector rounds up to a power of two.
fn allocSize(t: []const u8) u32 {
    const s = split(t);
    const bytes = s.n * scalarSize(s.scalar);
    return std.math.ceilPowerOfTwoAssert(u32, bytes);
}

/// The type a result is stored as.
fn storeType(a: Allocator, result: []const u8) ![]const u8 {
    if (std.mem.startsWith(u8, result, "S_")) return result[2..];
    const s = split(result);
    if (std.mem.eql(u8, s.scalar, "bool")) return if (s.n == 1) "u32" else try a.print("v{d}u32", .{s.n});
    return result;
}

/// The whole module for `p`.
pub fn moduleText(a: Allocator, p: Probe) ![]const u8 {
    var o: std.ArrayList(u8) = .empty;
    const ocl = p.flavour == .opencl;
    try o.print(a, "; probe {s}: generated by tools/spirv/probes.zig\n", .{p.name});
    if (ocl) {
        try o.appendSlice(a, "OpCapability Kernel\nOpCapability Addresses\nOpCapability Int64\nOpCapability Int16\nOpCapability Int8\nOpCapability Float16\n%ocl = OpExtInstImport \"OpenCL.std\"\nOpMemoryModel Physical64 OpenCL\n");
        try o.print(a, "OpEntryPoint Kernel %k \"{s}\" %gid\n", .{p.name});
    } else {
        try o.appendSlice(a, "OpCapability Shader\nOpCapability Int64\nOpCapability Int16\nOpCapability Int8\nOpCapability Float16\n%glsl = OpExtInstImport \"GLSL.std.450\"\nOpMemoryModel Logical GLSL450\n");
        try o.print(a, "OpEntryPoint GLCompute %k \"{s}\" %gid\nOpExecutionMode %k LocalSize 64 1 1\n", .{p.name});
    }
    try o.appendSlice(a, "OpDecorate %gid BuiltIn GlobalInvocationId\n");
    try o.appendSlice(a, p.decorations);
    const store_ty = try storeType(a, p.result);
    var buf_types: std.ArrayList([]const u8) = .empty;
    try buf_types.appendSlice(a, p.operands);
    try buf_types.append(a, store_ty);
    const out_index = buf_types.items.len - 1;
    if (!ocl) {
        for (buf_types.items, 0..) |t, i| {
            const binding = if (i == out_index) 3 else i;
            try o.print(a, "OpDecorate %rt{d} ArrayStride {d}\nOpDecorate %B{d} Block\nOpMemberDecorate %B{d} 0 Offset 0\nOpDecorate %buf{d} DescriptorSet 0\nOpDecorate %buf{d} Binding {d}\n", .{ i, allocSize(t), i, i, i, i, binding });
            if (i != out_index) try o.print(a, "OpDecorate %buf{d} NonWritable\n", .{i});
        }
    }
    try o.appendSlice(a, "%void = OpTypeVoid\n%fn = OpTypeFunction %void\n");
    for (scalars) |s| try o.print(a, "%{s} = {s}\n", .{ s.name, s.decl });
    for (scalars) |s| for ([_]u32{ 2, 3, 4 }) |n| try o.print(a, "%v{d}{s} = OpTypeVector %{s} {d}\n", .{ n, s.name, s.name, n });
    if (std.mem.startsWith(u8, p.result, "S_")) try o.print(a, "%{s} = OpTypeStruct %{s} %{s}\n", .{ p.result, store_ty, store_ty });
    try o.appendSlice(a, "%c0 = OpConstant %u32 0\n%one_u32 = OpConstant %u32 1\n%zero_u32 = OpConstant %u32 0\n");
    try o.appendSlice(a, p.types);
    for ([_]u32{ 2, 3, 4 }) |n| {
        try o.print(a, "%one_v{d}u32 = OpConstantComposite %v{d}u32", .{ n, n });
        for (0..n) |_| try o.appendSlice(a, " %one_u32");
        try o.print(a, "\n%zero_v{d}u32 = OpConstantComposite %v{d}u32", .{ n, n });
        for (0..n) |_| try o.appendSlice(a, " %zero_u32");
        try o.append(a, '\n');
    }
    const loads = [_][]const u8{ "%a", "%b", "%c" };
    if (ocl) {
        try o.appendSlice(a, "%pin = OpTypePointer Input %v3u64\n%gid = OpVariable %pin Input\n");
        for (buf_types.items, 0..) |t, i| try o.print(a, "%pe{d} = OpTypePointer CrossWorkgroup %{s}\n", .{ i, t });
        try o.appendSlice(a, "%fnk = OpTypeFunction %void");
        for (0..buf_types.items.len) |i| try o.print(a, " %pe{d}", .{i});
        try o.appendSlice(a, "\n%k = OpFunction %void None %fnk\n");
        for (0..buf_types.items.len) |i| try o.print(a, "%q{d} = OpFunctionParameter %pe{d}\n", .{ i, i });
        try o.appendSlice(a, "%e = OpLabel\n%gv = OpLoad %v3u64 %gid\n%g = OpCompositeExtract %u64 %gv 0\n");
        for (p.operands, 0..) |t, i| try o.print(a, "%p{d} = OpInBoundsPtrAccessChain %pe{d} %q{d} %g\n{s} = OpLoad %{s} %p{d}\n", .{ i, i, i, loads[i], t, i });
    } else {
        try o.appendSlice(a, "%pin = OpTypePointer Input %v3u32\n%gid = OpVariable %pin Input\n");
        for (buf_types.items, 0..) |t, i| {
            try o.print(a, "%rt{d} = OpTypeRuntimeArray %{s}\n%B{d} = OpTypeStruct %rt{d}\n%pB{d} = OpTypePointer StorageBuffer %B{d}\n%pe{d} = OpTypePointer StorageBuffer %{s}\n%buf{d} = OpVariable %pB{d} StorageBuffer\n", .{ i, t, i, i, i, i, i, t, i, i });
        }
        try o.appendSlice(a, "%k = OpFunction %void None %fn\n%e = OpLabel\n%gv = OpLoad %v3u32 %gid\n%g = OpCompositeExtract %u32 %gv 0\n");
        for (p.operands, 0..) |t, i| try o.print(a, "%p{d} = OpAccessChain %pe{d} %buf{d} %c0 %g\n{s} = OpLoad %{s} %p{d}\n", .{ i, i, i, loads[i], t, i });
    }
    try o.appendSlice(a, p.body);
    try o.append(a, '\n');
    // Epilogue: the value to store.
    const rs = split(p.result);
    if (std.mem.startsWith(u8, p.result, "S_")) {
        try o.print(a, "%m0 = OpCompositeExtract %{s} %r 0\n%m1 = OpCompositeExtract %{s} %r 1\n%st = OpBitwiseXor %{s} %m0 %m1\n", .{ store_ty, store_ty, store_ty });
    } else if (std.mem.eql(u8, rs.scalar, "bool")) {
        if (rs.n == 1) {
            try o.appendSlice(a, "%st = OpSelect %u32 %r %one_u32 %zero_u32\n");
        } else try o.print(a, "%st = OpSelect %v{d}u32 %r %one_v{d}u32 %zero_v{d}u32\n", .{ rs.n, rs.n, rs.n });
    } else try o.print(a, "%st = OpCopyObject %{s} %r\n", .{p.result});
    if (ocl) {
        try o.print(a, "%po = OpInBoundsPtrAccessChain %pe{d} %q{d} %g\n", .{ out_index, out_index });
    } else try o.print(a, "%po = OpAccessChain %pe{d} %buf{d} %c0 %g\n", .{ out_index, out_index });
    try o.appendSlice(a, "OpStore %po %st\nOpReturn\nOpFunctionEnd\n");
    return o.items;
}

// ── The probe set ───────────────────────────────────────────────────────────

const Gen = struct {
    a: Allocator,
    list: std.ArrayList(Probe) = .empty,

    fn add(g: *Gen, flavour: Flavour, name: []const u8, operands: []const []const u8, result: []const u8, body: []const u8) !void {
        try g.list.append(g.a, .{ .name = name, .flavour = flavour, .operands = try g.a.dupe([]const u8, operands), .result = result, .body = body });
    }

    /// A whole Probe (decorations, extra types); `operands` is copied.
    fn addProbe(g: *Gen, p: Probe) !void {
        var q = p;
        q.operands = try g.a.dupe([]const u8, p.operands);
        try g.list.append(g.a, q);
    }

    /// `%r = OpExtInst %R %set <inst> %a [%b [%c]]` for every type in `types`.
    fn ext(g: *Gen, flavour: Flavour, inst: []const u8, arity: usize, types: []const []const u8) !void {
        const set = if (flavour == .opencl) "ocl" else "glsl";
        for (types) |t| {
            const ops = [_][]const u8{ t, t, t };
            const args = [_][]const u8{ "", " %a", " %a %b", " %a %b %c" };
            try g.add(flavour, try g.a.print("{s}_{s}_{s}", .{ set, inst, t }), ops[0..arity], t, try g.a.print("%r = OpExtInst %{s} %{s} {s}{s}", .{ t, set, inst, args[arity] }));
        }
    }

    /// `%r = Op<inst> %R %a [%b]` with the result typed `result(t)`.
    fn op(g: *Gen, inst: []const u8, arity: usize, types: []const []const u8, bool_result: bool) !void {
        for (types) |t| {
            const ops = [_][]const u8{ t, t };
            const s = split(t);
            const r = if (bool_result) (if (s.n == 1) "bool" else try g.a.print("v{d}bool", .{s.n})) else t;
            const args = [_][]const u8{ "", " %a", " %a %b" };
            try g.add(.vulkan, try g.a.print("op_{s}_{s}", .{ inst, t }), ops[0..arity], r, try g.a.print("%r = Op{s} %{s}{s}", .{ inst, r, args[arity] }));
        }
    }
};

const glsl_float_unary = [_][]const u8{ "Round", "RoundEven", "Trunc", "FAbs", "FSign", "Floor", "Ceil", "Fract", "Radians", "Degrees", "Sin", "Cos", "Tan", "Asin", "Acos", "Atan", "Sinh", "Cosh", "Tanh", "Asinh", "Acosh", "Atanh", "Exp", "Log", "Exp2", "Log2", "Sqrt", "InverseSqrt" };
const glsl_float_binary = [_][]const u8{ "Atan2", "Pow", "FMin", "FMax", "NMin", "NMax", "Step" };
const glsl_float_ternary = [_][]const u8{ "FClamp", "NClamp", "FMix", "SmoothStep", "Fma" };
const glsl_int_unary = [_][]const u8{ "SAbs", "SSign", "FindILsb", "FindSMsb", "FindUMsb" };
const glsl_int_binary = [_][]const u8{ "SMin", "SMax", "UMin", "UMax" };
const glsl_int_ternary = [_][]const u8{ "SClamp", "UClamp" };
const float_types = [_][]const u8{ "f32", "v4f32", "f16" };

const ocl_float_unary = [_][]const u8{ "fabs", "sqrt", "rsqrt", "floor", "ceil", "trunc", "rint", "round", "sin", "cos", "tan", "asin", "acos", "atan", "sinh", "cosh", "tanh", "asinh", "acosh", "atanh", "exp", "exp2", "exp10", "log", "log2", "log10", "sign", "radians", "degrees" };
const ocl_float_binary = [_][]const u8{ "atan2", "pow", "powr", "fmin", "fmax", "step", "copysign", "fmod" };
const ocl_float_ternary = [_][]const u8{ "fma", "mad", "fclamp", "mix", "smoothstep" };
const ocl_int_unary = [_][]const u8{ "s_abs", "popcount", "clz", "ctz" };
const ocl_int_binary = [_][]const u8{ "s_min", "s_max", "u_min", "u_max", "s_mul_hi", "u_mul_hi" };
const ocl_int_ternary = [_][]const u8{ "s_clamp", "u_clamp" };

/// Every probe, in a fixed order.
pub fn all(a: Allocator) ![]const Probe {
    var g: Gen = .{ .a = a };
    // GLSL.std.450.
    for (glsl_float_unary) |n| try g.ext(.vulkan, n, 1, &float_types);
    for (glsl_float_binary) |n| try g.ext(.vulkan, n, 2, &float_types);
    for (glsl_float_ternary) |n| try g.ext(.vulkan, n, 3, &float_types);
    for (glsl_int_unary) |n| try g.ext(.vulkan, n, 1, &.{ "i32", "v4i32", "i64", "i16", "i8" });
    for (glsl_int_binary) |n| try g.ext(.vulkan, n, 2, &.{ "i32", "v4i32", "i64", "i16", "i8" });
    for (glsl_int_ternary) |n| try g.ext(.vulkan, n, 3, &.{ "i32", "v4i32", "i64", "i16", "i8" });
    for ([_][2][]const u8{ .{ "f32", "i32" }, .{ "v4f32", "v4i32" }, .{ "f16", "i32" } }) |p| {
        try g.add(.vulkan, try a.print("glsl_Ldexp_{s}", .{p[0]}), &.{ p[0], p[1] }, p[0], try a.print("%r = OpExtInst %{s} %glsl Ldexp %a %b", .{p[0]}));
    }
    for ([_][]const u8{ "f32", "v2f32", "v3f32", "v4f32", "v4f16" }) |t| {
        const s = split(t).scalar;
        try g.add(.vulkan, try a.print("glsl_Length_{s}", .{t}), &.{t}, s, try a.print("%r = OpExtInst %{s} %glsl Length %a", .{s}));
        try g.add(.vulkan, try a.print("glsl_Distance_{s}", .{t}), &.{ t, t }, s, try a.print("%r = OpExtInst %{s} %glsl Distance %a %b", .{s}));
        try g.add(.vulkan, try a.print("glsl_Normalize_{s}", .{t}), &.{t}, t, try a.print("%r = OpExtInst %{s} %glsl Normalize %a", .{t}));
    }
    for ([_][]const u8{ "v3f32", "v3f16" }) |t| try g.add(.vulkan, try a.print("glsl_Cross_{s}", .{t}), &.{ t, t }, t, try a.print("%r = OpExtInst %{s} %glsl Cross %a %b", .{t}));

    // OpenCL.std, in the OpenCL flavour.
    for (ocl_float_unary) |n| try g.ext(.opencl, n, 1, &.{ "f32", "v4f32" });
    for (ocl_float_binary) |n| try g.ext(.opencl, n, 2, &.{ "f32", "v4f32" });
    for (ocl_float_ternary) |n| try g.ext(.opencl, n, 3, &.{ "f32", "v4f32" });
    for (ocl_int_unary) |n| try g.ext(.opencl, n, 1, &.{ "u32", "v4u32", "u64" });
    for (ocl_int_binary) |n| try g.ext(.opencl, n, 2, &.{ "u32", "v4u32", "u64" });
    for (ocl_int_ternary) |n| try g.ext(.opencl, n, 3, &.{ "u32", "v4u32" });
    for ([_][2][]const u8{ .{ "f32", "u32" }, .{ "v4f32", "v4u32" } }) |p| {
        try g.add(.opencl, try a.print("ocl_ldexp_{s}", .{p[0]}), &.{ p[0], p[1] }, p[0], try a.print("%r = OpExtInst %{s} %ocl ldexp %a %b", .{p[0]}));
    }
    for ([_][]const u8{ "f32", "v3f32", "v4f32" }) |t| {
        const s = split(t).scalar;
        try g.add(.opencl, try a.print("ocl_length_{s}", .{t}), &.{t}, s, try a.print("%r = OpExtInst %{s} %ocl length %a", .{s}));
        try g.add(.opencl, try a.print("ocl_distance_{s}", .{t}), &.{ t, t }, s, try a.print("%r = OpExtInst %{s} %ocl distance %a %b", .{s}));
        try g.add(.opencl, try a.print("ocl_normalize_{s}", .{t}), &.{t}, t, try a.print("%r = OpExtInst %{s} %ocl normalize %a", .{t}));
    }
    for ([_][]const u8{ "v3f32", "v4f32" }) |t| try g.add(.opencl, try a.print("ocl_cross_{s}", .{t}), &.{ t, t }, t, try a.print("%r = OpExtInst %{s} %ocl cross %a %b", .{t}));

    // Core arithmetic.
    const int_types = [_][]const u8{ "i32", "i64", "i16", "i8", "v4i32" };
    for ([_][]const u8{ "IAdd", "ISub", "IMul", "SDiv", "UDiv", "SRem", "SMod", "UMod", "BitwiseAnd", "BitwiseOr", "BitwiseXor", "ShiftLeftLogical", "ShiftRightLogical", "ShiftRightArithmetic" }) |n| try g.op(n, 2, &int_types, false);
    for ([_][]const u8{ "SNegate", "Not", "BitCount", "BitReverse" }) |n| try g.op(n, 1, &.{ "i32", "i64", "i16", "v4i32", "i8" }, false);
    for ([_][]const u8{ "FAdd", "FSub", "FMul", "FDiv", "FRem", "FMod" }) |n| try g.op(n, 2, &float_types, false);
    try g.op("FNegate", 1, &float_types, false);
    for ([_][]const u8{ "IEqual", "INotEqual", "UGreaterThan", "SGreaterThan", "UGreaterThanEqual", "SGreaterThanEqual", "ULessThan", "SLessThan", "ULessThanEqual", "SLessThanEqual" }) |n| try g.op(n, 2, &.{ "i32", "i64", "v4i32", "i16", "i8" }, true);
    for ([_][]const u8{ "FOrdEqual", "FUnordEqual", "FOrdNotEqual", "FUnordNotEqual", "FOrdLessThan", "FUnordLessThan", "FOrdGreaterThan", "FUnordGreaterThan", "FOrdLessThanEqual", "FUnordLessThanEqual", "FOrdGreaterThanEqual", "FUnordGreaterThanEqual", "Ordered", "Unordered" }) |n| try g.op(n, 2, &float_types, true);
    for ([_][]const u8{ "IsNan", "IsInf", "IsFinite" }) |n| try g.op(n, 1, &float_types, true);
    // Logical operations on comparison results; select with scalar and vector conditions.
    for ([_][]const u8{ "LogicalAnd", "LogicalOr", "LogicalEqual", "LogicalNotEqual" }) |n| {
        for ([_][]const u8{ "i32", "v4i32" }) |t| {
            const s = split(t);
            const bt = if (s.n == 1) "bool" else try a.print("v{d}bool", .{s.n});
            try g.add(.vulkan, try a.print("op_{s}_{s}", .{ n, t }), &.{ t, t }, bt, try a.print("%x = OpSLessThan %{s} %a %b\n%y = OpIEqual %{s} %a %b\n%r = Op{s} %{s} %x %y", .{ bt, bt, n, bt }));
        }
    }
    for ([_][]const u8{ "i32", "v4i32" }) |t| {
        const s = split(t);
        const bt = if (s.n == 1) "bool" else try a.print("v{d}bool", .{s.n});
        try g.add(.vulkan, try a.print("op_LogicalNot_{s}", .{t}), &.{ t, t }, bt, try a.print("%x = OpSLessThan %{s} %a %b\n%r = OpLogicalNot %{s} %x", .{ bt, bt }));
        try g.add(.vulkan, try a.print("op_Select_{s}", .{t}), &.{ t, t }, t, try a.print("%x = OpSLessThan %{s} %a %b\n%r = OpSelect %{s} %x %a %b", .{ bt, t }));
    }
    try g.add(.vulkan, "op_Select_scalar_cond_v4f32", &.{ "v4f32", "f32", "f32" }, "v4f32", "%x = OpFOrdLessThan %bool %b %c\n%r = OpSelect %v4f32 %x %a %a");
    try g.add(.vulkan, "op_Any_v4bool", &.{ "v4i32", "v4i32" }, "bool", "%x = OpSLessThan %v4bool %a %b\n%r = OpAny %bool %x");
    for ([_]u32{ 2, 3, 4 }) |n| {
        try g.add(.vulkan, try a.print("op_All_v{d}bool", .{n}), &.{ try a.print("v{d}i32", .{n}), try a.print("v{d}i32", .{n}) }, "bool", try a.print("%x = OpSLessThan %v{d}bool %a %b\n%r = OpAll %bool %x", .{n}));
    }

    // Conversions.
    const ints = [_][]const u8{ "u8", "u16", "u32", "u64" };
    for (ints) |from| for (ints) |to| {
        if (std.mem.eql(u8, from, to)) continue;
        try g.add(.vulkan, try a.print("conv_UConvert_{s}_{s}", .{ from, to }), &.{from}, to, try a.print("%r = OpUConvert %{s} %a", .{to}));
        const sf = try a.print("i{s}", .{from[1..]});
        const st = try a.print("i{s}", .{to[1..]});
        try g.add(.vulkan, try a.print("conv_SConvert_{s}_{s}", .{ sf, st }), &.{sf}, st, try a.print("%r = OpSConvert %{s} %a", .{st}));
    };
    try g.add(.vulkan, "conv_FConvert_f16_f32", &.{"f16"}, "f32", "%r = OpFConvert %f32 %a");
    try g.add(.vulkan, "conv_FConvert_f32_f16", &.{"f32"}, "f16", "%r = OpFConvert %f16 %a");
    try g.add(.vulkan, "conv_FConvert_v4f32_v4f16", &.{"v4f32"}, "v4f16", "%r = OpFConvert %v4f16 %a");
    for ([_][]const u8{ "f32", "f16" }) |f| {
        for ([_][]const u8{ "i8", "i16", "i32", "i64" }) |i| {
            const u = try a.print("u{s}", .{i[1..]});
            try g.add(.vulkan, try a.print("conv_ConvertFToS_{s}_{s}", .{ f, i }), &.{f}, i, try a.print("%r = OpConvertFToS %{s} %a", .{i}));
            try g.add(.vulkan, try a.print("conv_ConvertFToU_{s}_{s}", .{ f, u }), &.{f}, u, try a.print("%r = OpConvertFToU %{s} %a", .{u}));
            try g.add(.vulkan, try a.print("conv_ConvertSToF_{s}_{s}", .{ i, f }), &.{i}, f, try a.print("%r = OpConvertSToF %{s} %a", .{f}));
            try g.add(.vulkan, try a.print("conv_ConvertUToF_{s}_{s}", .{ u, f }), &.{u}, f, try a.print("%r = OpConvertUToF %{s} %a", .{f}));
        }
    }
    try g.add(.vulkan, "conv_ConvertFToS_v4f32_v4i32", &.{"v4f32"}, "v4i32", "%r = OpConvertFToS %v4i32 %a");
    try g.add(.vulkan, "conv_ConvertUToF_v4u32_v4f32", &.{"v4u32"}, "v4f32", "%r = OpConvertUToF %v4f32 %a");
    for ([_][2][]const u8{ .{ "u32", "f32" }, .{ "f32", "i32" }, .{ "u16", "f16" }, .{ "f16", "i16" }, .{ "v2u32", "u64" }, .{ "u64", "v2f32" }, .{ "v4f16", "v2u32" }, .{ "v4u8", "u32" } }) |p| {
        try g.add(.vulkan, try a.print("conv_Bitcast_{s}_{s}", .{ p[0], p[1] }), &.{p[0]}, p[1], try a.print("%r = OpBitcast %{s} %a", .{p[1]}));
    }

    // Wide arithmetic and bit fields.
    for ([_][]const u8{ "IAddCarry", "ISubBorrow", "UMulExtended", "SMulExtended" }) |n| {
        for ([_][]const u8{ "u32", "u64", "v4u32", "u16" }) |t| {
            try g.add(.vulkan, try a.print("op_{s}_{s}", .{ n, t }), &.{ t, t }, try a.print("S_{s}", .{t}), try a.print("%r = Op{s} %S_{s} %a %b", .{ n, t }));
        }
    }
    for ([_][]const u8{ "u32", "i64", "v4u32", "u16" }) |t| {
        try g.add(.vulkan, try a.print("op_BitFieldUExtract_{s}", .{t}), &.{ t, "u32", "u32" }, t, try a.print("%r = OpBitFieldUExtract %{s} %a %b %c", .{t}));
        try g.add(.vulkan, try a.print("op_BitFieldSExtract_{s}", .{t}), &.{ t, "u32", "u32" }, t, try a.print("%r = OpBitFieldSExtract %{s} %a %b %c", .{t}));
        try g.add(.vulkan, try a.print("op_BitFieldInsert_{s}", .{t}), &.{ t, t, "u32" }, t, try a.print("%r = OpBitFieldInsert %{s} %a %b %c %c", .{t}));
    }

    // Vectors and composites.
    try g.add(.vulkan, "vec_VectorShuffle_v4f32", &.{ "v4f32", "v4f32" }, "v4f32", "%r = OpVectorShuffle %v4f32 %a %b 7 0 4294967295 2");
    try g.add(.vulkan, "vec_VectorShuffle_v2f32_v4f32", &.{ "v2f32", "v4f32" }, "v3f32", "%r = OpVectorShuffle %v3f32 %a %b 5 1 0");
    try g.add(.vulkan, "vec_VectorExtractDynamic_v4f32", &.{ "v4f32", "u32" }, "f32", "%r = OpVectorExtractDynamic %f32 %a %b");
    try g.add(.vulkan, "vec_VectorInsertDynamic_v4f32", &.{ "v4f32", "f32", "u32" }, "v4f32", "%r = OpVectorInsertDynamic %v4f32 %a %b %c");
    try g.add(.vulkan, "vec_VectorTimesScalar_v4f32", &.{ "v4f32", "f32" }, "v4f32", "%r = OpVectorTimesScalar %v4f32 %a %b");
    try g.add(.vulkan, "vec_VectorTimesScalar_v3f16", &.{ "v3f16", "f16" }, "v3f16", "%r = OpVectorTimesScalar %v3f16 %a %b");
    for ([_][]const u8{ "v2f32", "v3f32", "v4f32", "v4f16", "v2f16" }) |t| {
        const s = split(t).scalar;
        try g.add(.vulkan, try a.print("vec_Dot_{s}", .{t}), &.{ t, t }, s, try a.print("%r = OpDot %{s} %a %b", .{s}));
    }
    try g.add(.vulkan, "vec_CompositeConstruct_v4f32", &.{ "v2f32", "f32" }, "v4f32", "%r = OpCompositeConstruct %v4f32 %a %b %b");
    try g.add(.vulkan, "vec_CompositeExtractInsert_v3u8", &.{ "v3u8", "u8" }, "v3u8", "%x = OpCompositeExtract %u8 %a 2\n%y = OpIAdd %u8 %x %b\n%r = OpCompositeInsert %v3u8 %y %a 0");

    // OpSelect of composites (SPIR-V 1.4), lowered member by member: an
    // aggregate `select` of `{ i32, <4 x i32> }` crashes MTLCompilerService.
    try g.addProbe(.{ .name = "comp_Select_struct_u32_v4u32", .operands = &.{ "u32", "v4u32", "u32" }, .result = "v4u32", .types = "%Sq = OpTypeStruct %u32 %v4u32\n", .body =
        \\%bb = OpIAdd %v4u32 %b %b
        \\%s1 = OpCompositeConstruct %Sq %a %b
        \\%s2 = OpCompositeConstruct %Sq %c %bb
        \\%lt = OpULessThan %bool %a %c
        \\%sel = OpSelect %Sq %lt %s1 %s2
        \\%m0 = OpCompositeExtract %u32 %sel 0
        \\%m1 = OpCompositeExtract %v4u32 %sel 1
        \\%r = OpCompositeInsert %v4u32 %m0 %m1 0
    });
    try g.addProbe(.{ .name = "comp_Select_array_u32", .operands = &.{ "u32", "u32", "u32" }, .result = "v2u32", .types = "%c2 = OpConstant %u32 2\n%A2 = OpTypeArray %u32 %c2\n", .body =
        \\%x1 = OpCompositeConstruct %A2 %a %b
        \\%x2 = OpCompositeConstruct %A2 %b %c
        \\%lt = OpULessThan %bool %a %c
        \\%sel = OpSelect %A2 %lt %x1 %x2
        \\%e0 = OpCompositeExtract %u32 %sel 0
        \\%e1 = OpCompositeExtract %u32 %sel 1
        \\%r = OpCompositeConstruct %v2u32 %e0 %e1
    });
    try g.addProbe(.{ .name = "comp_Select_nested_bool_v3u32", .operands = &.{ "v3u32", "u32", "u32" }, .result = "v4u32", .types = "%Sb = OpTypeStruct %bool %v3u32\n%Sn = OpTypeStruct %Sb %u32\n", .body =
        \\%lt = OpULessThan %bool %b %c
        \\%aa = OpIAdd %v3u32 %a %a
        \\%i1 = OpCompositeConstruct %Sb %lt %a
        \\%o1 = OpCompositeConstruct %Sn %i1 %b
        \\%i2 = OpCompositeConstruct %Sb %lt %aa
        \\%o2 = OpCompositeConstruct %Sn %i2 %c
        \\%sel = OpSelect %Sn %lt %o1 %o2
        \\%flag = OpCompositeExtract %bool %sel 0 0
        \\%v = OpCompositeExtract %v3u32 %sel 0 1
        \\%n = OpCompositeExtract %u32 %sel 1
        \\%fv = OpSelect %u32 %flag %one_u32 %zero_u32
        \\%w = OpIAdd %u32 %n %fv
        \\%x = OpCompositeExtract %u32 %v 0
        \\%y = OpCompositeExtract %u32 %v 1
        \\%z = OpCompositeExtract %u32 %v 2
        \\%r = OpCompositeConstruct %v4u32 %x %y %z %w
    });

    // Conversions carrying SaturatedConversion (OpenCL convert_<T>_sat)
    // and FPRoundingMode (convert_<T>_rte/_rtp/_rtn).
    const sat = "OpDecorate %r SaturatedConversion\n";
    for ([_][2][]const u8{ .{ "u32", "u8" }, .{ "u64", "u16" }, .{ "u64", "u32" }, .{ "v4u32", "v4u8" }, .{ "u16", "u32" } }) |c| {
        try g.addProbe(.{ .name = try a.print("conv_UConvertSat_{s}_{s}", .{ c[0], c[1] }), .operands = &.{c[0]}, .result = c[1], .decorations = sat, .body = try a.print("%r = OpUConvert %{s} %a", .{c[1]}) });
    }
    for ([_][2][]const u8{ .{ "i32", "i8" }, .{ "i64", "i32" }, .{ "i16", "i8" }, .{ "v4i32", "v4i16" } }) |c| {
        try g.addProbe(.{ .name = try a.print("conv_SConvertSat_{s}_{s}", .{ c[0], c[1] }), .operands = &.{c[0]}, .result = c[1], .decorations = sat, .body = try a.print("%r = OpSConvert %{s} %a", .{c[1]}) });
    }
    for ([_][2][]const u8{ .{ "f32", "i32" }, .{ "f32", "i8" }, .{ "f32", "i64" }, .{ "f16", "i32" }, .{ "f16", "i8" }, .{ "v4f32", "v4i32" } }) |c| {
        try g.addProbe(.{ .name = try a.print("conv_ConvertFToSSat_{s}_{s}", .{ c[0], c[1] }), .operands = &.{c[0]}, .result = c[1], .decorations = sat, .body = try a.print("%r = OpConvertFToS %{s} %a", .{c[1]}) });
    }
    for ([_][2][]const u8{ .{ "f32", "u32" }, .{ "f32", "u8" }, .{ "f32", "u64" }, .{ "f16", "u32" }, .{ "f16", "u16" } }) |c| {
        try g.addProbe(.{ .name = try a.print("conv_ConvertFToUSat_{s}_{s}", .{ c[0], c[1] }), .operands = &.{c[0]}, .result = c[1], .decorations = sat, .body = try a.print("%r = OpConvertFToU %{s} %a", .{c[1]}) });
    }
    for ([_][2][]const u8{ .{ "Rte", "RTE" }, .{ "Rtp", "RTP" }, .{ "Rtn", "RTN" } }) |m| {
        for ([_][2][]const u8{ .{ "f32", "i32" }, .{ "f16", "i16" }, .{ "v4f32", "v4i32" } }) |c| {
            try g.addProbe(.{ .name = try a.print("conv_ConvertFToS{s}_{s}_{s}", .{ m[0], c[0], c[1] }), .operands = &.{c[0]}, .result = c[1], .decorations = try a.print("OpDecorate %r FPRoundingMode {s}\n", .{m[1]}), .body = try a.print("%r = OpConvertFToS %{s} %a", .{c[1]}) });
        }
        try g.addProbe(.{ .name = try a.print("conv_ConvertFToU{s}_f32_u32", .{m[0]}), .operands = &.{"f32"}, .result = "u32", .decorations = try a.print("OpDecorate %r FPRoundingMode {s}\n", .{m[1]}), .body = "%r = OpConvertFToU %u32 %a" });
        try g.addProbe(.{ .name = try a.print("conv_ConvertFToSSat{s}_f32_i8", .{m[0]}), .operands = &.{"f32"}, .result = "i8", .decorations = try a.print("OpDecorate %r FPRoundingMode {s}\n" ++ sat, .{m[1]}), .body = "%r = OpConvertFToS %i8 %a" });
    }
    try stage4(&g);
    return g.list.items;
}

/// Scope and semantics constants for the stage-4 probes: `%s_dev` Device,
/// `%s_wg` Workgroup, `%s_sg` Subgroup; `%m_*` MemorySemantics (relaxed,
/// acquire / release / acq_rel / seq_cst with UniformMemory or
/// WorkgroupMemory, and the storage-class bits alone).
const stage4_types =
    \\%s_dev = OpConstant %u32 1
    \\%s_wg = OpConstant %u32 2
    \\%s_sg = OpConstant %u32 3
    \\%m_relaxed = OpConstant %u32 0
    \\%m_acq_dev = OpConstant %u32 66
    \\%m_rel_dev = OpConstant %u32 68
    \\%m_ar_dev = OpConstant %u32 72
    \\%m_sc_dev = OpConstant %u32 80
    \\%m_acq_wg = OpConstant %u32 258
    \\%m_rel_wg = OpConstant %u32 260
    \\%m_ar_wg = OpConstant %u32 264
    \\%m_sc_wg = OpConstant %u32 272
    \\%m_ar = OpConstant %u32 8
    \\%m_ar_both = OpConstant %u32 328
    \\%m_ar_image = OpConstant %u32 2056
    \\
;

/// Stage 4 (docs/spirv.md "Barriers and atomics"): one probe per atomic
/// instruction at each type Metal might have (u32, u64, f32) on a device
/// pointer (`_dev`: the output buffer's element) and on a threadgroup one
/// (`_tg`: a Workgroup variable), each memory ordering on a device and a
/// threadgroup IAdd / Load / Store / CompareExchange, and every barrier
/// and fence form the lowering emits. Built into pipelines only
/// (reference.checkOf skips `atom_` / `sync_`), so a construct Metal's
/// compiler refuses or crashes on is attributable to one instruction; the
/// outcome of each is in tools/spirv/corpus/EXPECTED.txt.
fn stage4(g: *Gen) !void {
    const a = g.a;
    const rmw = [_][]const u8{ "Exchange", "IAdd", "ISub", "SMin", "UMin", "SMax", "UMax", "And", "Or", "Xor" };
    for ([_][]const u8{ "u32", "u64" }) |t| {
        for ([_]bool{ false, true }) |tg| {
            const space = if (tg) "tg" else "dev";
            const types = try a.print("{s}%pwg = OpTypePointer Workgroup %{s}\n%wg = OpVariable %pwg Workgroup\n", .{ stage4_types, t });
            // The device pointer: the output element (operand 1 is the
            // output buffer, `%pe1` / `%buf1`).
            const ptr = if (tg) "%wg" else "%pa";
            const pre = if (tg) "" else "%pa = OpAccessChain %pe1 %buf1 %c0 %g\n";
            const sc = if (tg) "%s_wg" else "%s_dev";
            const wide = std.mem.eql(u8, t, "u64");
            // 64 bits: Metal has load, store, and min/max on device memory
            // whose result is unused (MSL's atomic_ulong min/max return
            // void); the lowering refuses the rest (lower.zig `atomic`).
            const other64 = "Metal has 64-bit atomic load, store, min and max only";
            for (rmw) |op| {
                const minmax = std.mem.endsWith(u8, op, "Min") or std.mem.endsWith(u8, op, "Max");
                if (wide and minmax and !tg) {
                    // The supported shape: the old value is not used.
                    try g.addProbe(.{ .name = try a.print("atom_{s}_{s}_{s}", .{ op, t, space }), .operands = &.{t}, .result = t, .types = types, .body = try a.print("{s}%unused = OpAtomic{s} %{s} {s} {s} %m_relaxed %a\n%r = OpCopyObject %{s} %a", .{ pre, op, t, ptr, sc, t }) });
                    try g.addProbe(.{ .name = try a.print("atom_{s}_{s}_{s}_result", .{ op, t, space }), .operands = &.{t}, .result = t, .types = types, .refused = "the result of a 64-bit atomic min/max is used", .body = try a.print("{s}%r = OpAtomic{s} %{s} {s} {s} %m_relaxed %a", .{ pre, op, t, ptr, sc }) });
                    continue;
                }
                const refused: ?[]const u8 = if (!wide) null else if (minmax) "64-bit atomic min/max on threadgroup memory" else other64;
                try g.addProbe(.{ .name = try a.print("atom_{s}_{s}_{s}", .{ op, t, space }), .operands = &.{t}, .result = t, .types = types, .refused = refused, .body = try a.print("{s}%r = OpAtomic{s} %{s} {s} {s} %m_relaxed %a", .{ pre, op, t, ptr, sc }) });
            }
            for ([_][]const u8{ "IIncrement", "IDecrement" }) |op| {
                try g.addProbe(.{ .name = try a.print("atom_{s}_{s}_{s}", .{ op, t, space }), .operands = &.{t}, .result = t, .types = types, .refused = if (wide) other64 else null, .body = try a.print("{s}%r = OpAtomic{s} %{s} {s} {s} %m_relaxed", .{ pre, op, t, ptr, sc }) });
            }
            try g.addProbe(.{ .name = try a.print("atom_Load_{s}_{s}", .{ t, space }), .operands = &.{t}, .result = t, .types = types, .body = try a.print("{s}%r = OpAtomicLoad %{s} {s} {s} %m_relaxed", .{ pre, t, ptr, sc }) });
            try g.addProbe(.{ .name = try a.print("atom_Store_{s}_{s}", .{ t, space }), .operands = &.{t}, .result = t, .types = types, .body = try a.print("{s}OpAtomicStore {s} {s} %m_relaxed %a\n%r = OpCopyObject %{s} %a", .{ pre, ptr, sc, t }) });
            try g.addProbe(.{ .name = try a.print("atom_CompareExchange_{s}_{s}", .{ t, space }), .operands = &.{t}, .result = t, .types = types, .refused = if (wide) "64-bit OpAtomicCompareExchange" else null, .body = try a.print("{s}%r = OpAtomicCompareExchange %{s} {s} {s} %m_relaxed %m_relaxed %a %a", .{ pre, t, ptr, sc }) });
        }
    }
    // Float atomics (SPV_EXT_shader_atomic_float_add / _min_max) and the
    // float forms of Load, Store and Exchange.
    for ([_]bool{ false, true }) |tg| {
        const space = if (tg) "tg" else "dev";
        const types = try a.print("{s}%pwg = OpTypePointer Workgroup %f32\n%wg = OpVariable %pwg Workgroup\n", .{stage4_types});
        const ptr = if (tg) "%wg" else "%pa";
        const pre = if (tg) "" else "%pa = OpAccessChain %pe1 %buf1 %c0 %g\n";
        const sc = if (tg) "%s_wg" else "%s_dev";
        for ([_][]const u8{ "FAddEXT", "FMinEXT", "FMaxEXT", "Exchange" }) |op| {
            // Threadgroup float add builds but computes a wrong sum on
            // Metal (corpus kernel hand-workgroup-atomics:atomic_fadd_tg).
            const refused: ?[]const u8 = if (std.mem.eql(u8, op, "FMinEXT") or std.mem.eql(u8, op, "FMaxEXT")) "does not know `atomicrmw fmin/fmax`" else if (tg and std.mem.eql(u8, op, "FAddEXT")) "OpAtomicFAddEXT on threadgroup memory" else null;
            try g.addProbe(.{ .name = try a.print("atom_{s}_f32_{s}", .{ op, space }), .operands = &.{"f32"}, .result = "f32", .types = types, .refused = refused, .body = try a.print("{s}%r = OpAtomic{s} %f32 {s} {s} %m_relaxed %a", .{ pre, op, ptr, sc }) });
        }
        try g.addProbe(.{ .name = try a.print("atom_Load_f32_{s}", .{space}), .operands = &.{"f32"}, .result = "f32", .types = types, .body = try a.print("{s}%r = OpAtomicLoad %f32 {s} {s} %m_relaxed", .{ pre, ptr, sc }) });
        try g.addProbe(.{ .name = try a.print("atom_Store_f32_{s}", .{space}), .operands = &.{"f32"}, .result = "f32", .types = types, .body = try a.print("{s}OpAtomicStore {s} {s} %m_relaxed %a\n%r = OpCopyObject %f32 %a", .{ pre, ptr, sc }) });
    }
    // Every ordering, on both spaces (u32).
    for ([_]bool{ false, true }) |tg| {
        const space = if (tg) "tg" else "dev";
        const types = try a.print("{s}%pwg = OpTypePointer Workgroup %u32\n%wg = OpVariable %pwg Workgroup\n", .{stage4_types});
        const ptr = if (tg) "%wg" else "%pa";
        const pre = if (tg) "" else "%pa = OpAccessChain %pe1 %buf1 %c0 %g\n";
        const sc = if (tg) "%s_wg" else "%s_dev";
        const sfx = if (tg) "wg" else "dev";
        for ([_][]const u8{ "acq", "rel", "ar", "sc" }) |o| {
            try g.addProbe(.{ .name = try a.print("atom_IAdd_{s}_u32_{s}", .{ o, space }), .operands = &.{"u32"}, .result = "u32", .types = types, .body = try a.print("{s}%r = OpAtomicIAdd %u32 {s} {s} %m_{s}_{s} %a", .{ pre, ptr, sc, o, sfx }) });
        }
        for ([_][]const u8{ "acq", "ar", "sc" }) |o| {
            try g.addProbe(.{ .name = try a.print("atom_Load_{s}_u32_{s}", .{ o, space }), .operands = &.{"u32"}, .result = "u32", .types = types, .body = try a.print("{s}%r = OpAtomicLoad %u32 {s} {s} %m_{s}_{s}", .{ pre, ptr, sc, o, sfx }) });
        }
        for ([_][]const u8{ "rel", "ar", "sc" }) |o| {
            try g.addProbe(.{ .name = try a.print("atom_Store_{s}_u32_{s}", .{ o, space }), .operands = &.{"u32"}, .result = "u32", .types = types, .body = try a.print("{s}OpAtomicStore {s} {s} %m_{s}_{s} %a\n%r = OpCopyObject %u32 %a", .{ pre, ptr, sc, o, sfx }) });
        }
        for ([_][2][]const u8{ .{ "ar", "acq" }, .{ "sc", "sc" }, .{ "rel", "relaxed" } }) |o| {
            const eq = try a.print("%m_{s}_{s}", .{ o[0], sfx });
            const ne = if (std.mem.eql(u8, o[1], "relaxed")) "%m_relaxed" else try a.print("%m_{s}_{s}", .{ o[1], sfx });
            try g.addProbe(.{ .name = try a.print("atom_CompareExchange_{s}_{s}_u32_{s}", .{ o[0], o[1], space }), .operands = &.{"u32"}, .result = "u32", .types = types, .body = try a.print("{s}%r = OpAtomicCompareExchange %u32 {s} {s} {s} {s} %a %a", .{ pre, ptr, sc, eq, ne }) });
        }
    }
    // Barriers and fences: every flag combination the lowering emits.
    const barriers = [_][3][]const u8{
        .{ "wg_tg", "%s_wg", "%m_ar_wg" }, // GLSL barrier(): air.wg.barrier(2, 1)
        .{ "wg_none", "%s_wg", "%m_ar" }, // mem_none
        .{ "wg_dev", "%s_wg", "%m_ar_dev" }, // mem_device
        .{ "wg_both", "%s_wg", "%m_ar_both" }, // mem_device | mem_threadgroup
        .{ "wg_image", "%s_wg", "%m_ar_image" }, // mem_texture
        .{ "sg_tg", "%s_sg", "%m_ar_wg" }, // air.simdgroup.barrier(2, 4)
        .{ "sg_none", "%s_sg", "%m_ar" },
    };
    for (barriers) |b| {
        try g.addProbe(.{ .name = try a.print("sync_ControlBarrier_{s}", .{b[0]}), .operands = &.{"u32"}, .result = "u32", .types = stage4_types, .body = try a.print("OpControlBarrier {s} {s} {s}\n%r = OpCopyObject %u32 %a", .{ b[1], b[1], b[2] }) });
    }
    // Memory scope Device with UniformMemory: a device fence, then the barrier.
    try g.addProbe(.{ .name = "sync_ControlBarrier_wg_devscope", .operands = &.{"u32"}, .result = "u32", .types = stage4_types, .body = "OpControlBarrier %s_wg %s_dev %m_ar_dev\n%r = OpCopyObject %u32 %a" });
    // A Subgroup barrier with a wider memory scope: a fence at that scope
    // (threadgroup: air.atomic.fence(2, 5, 1); device: (1, 5, 2)), then
    // air.simdgroup.barrier.
    try g.addProbe(.{ .name = "sync_ControlBarrier_sg_wgscope", .operands = &.{"u32"}, .result = "u32", .types = stage4_types, .body = "OpControlBarrier %s_sg %s_wg %m_ar_wg\n%r = OpCopyObject %u32 %a" });
    try g.addProbe(.{ .name = "sync_ControlBarrier_sg_devscope", .operands = &.{"u32"}, .result = "u32", .types = stage4_types, .body = "OpControlBarrier %s_sg %s_dev %m_ar_dev\n%r = OpCopyObject %u32 %a" });
    const fences = [_][3][]const u8{
        .{ "dev_dev", "%s_dev", "%m_ar_dev" }, // air.atomic.fence(1, 5, 2)
        .{ "wg_tg", "%s_wg", "%m_ar_wg" }, // (2, 5, 1)
        .{ "sg_tg", "%s_sg", "%m_ar_wg" }, // (2, 5, 4)
        .{ "dev_both", "%s_dev", "%m_ar_both" }, // (3, 5, 2)
        .{ "wg_dev", "%s_wg", "%m_ar_dev" }, // (1, 5, 1)
        .{ "dev_image", "%s_dev", "%m_ar_image" }, // (4, 5, 2)
    };
    for (fences) |b| {
        try g.addProbe(.{ .name = try a.print("sync_MemoryBarrier_{s}", .{b[0]}), .operands = &.{"u32"}, .result = "u32", .types = stage4_types, .body = try a.print("OpMemoryBarrier {s} {s}\n%r = OpCopyObject %u32 %a", .{ b[1], b[2] }) });
    }
}

